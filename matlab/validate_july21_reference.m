% Validate the MATLAB workflow against the audited July 21-22 reference pair.
% This script exports a hidden test figure and checks the expected metrics.

matlabFolder = fileparts(mfilename('fullpath'));
repositoryRoot = fileparts(matlabFolder);
addpath(matlabFolder);

jetsonJson = fullfile(repositoryRoot, 'supplementary', 'july21_2026', ...
    'sleep_log_20260721 (1).json');
swarmCsv = fullfile(repositoryRoot, ...
    'BRAID_24hr-260304-154142_JL-260721-180219_Cam1.avi_Tracker_DataComputer_2026-07-22 03-46-21.csv');
outputFile = fullfile(repositoryRoot, 'outputs', ...
    'jetson_swarmsight_matlab', 'july-21-22-2026-validation.png');

result = plot_jetson_swarmsight(jetsonJson, swarmCsv, ...
    'VideoStart', datetime(2026, 7, 21, 18, 2, 19), ...
    'FrameRate', 5, ...
    'Label', 'July 21-22, 2026 validation', ...
    'OutputFile', outputFile, ...
    'Visible', 'off');

expected = struct( ...
    'InputFrames', 327665, ...
    'JetsonBoutCount', 37, ...
    'SwarmSightLowPeriodCount', 42, ...
    'ThresholdDegPerSecond', 18.4869607200, ...
    'SpeedCapDegPerSecond', 257.5990087583, ...
    'Agreement', 0.8621427480, ...
    'Sensitivity', 0.8663777537, ...
    'Specificity', 0.8590355061, ...
    'Precision', 0.8184919823, ...
    'Jaccard', 0.7267494699);

assert(result.Metrics.InputFrames == expected.InputFrames, ...
    'Unexpected SwarmSight frame count.');
assert(result.Metrics.JetsonBoutCount == expected.JetsonBoutCount, ...
    'Unexpected Jetson bout count.');
assert(result.Metrics.SwarmSightLowPeriodCount == expected.SwarmSightLowPeriodCount, ...
    'Unexpected SwarmSight low-period count.');
assertClose(result.Metrics.ThresholdDegPerSecond, ...
    expected.ThresholdDegPerSecond, 1e-6, 'threshold');
assertClose(result.Metrics.SpeedCapDegPerSecond, ...
    expected.SpeedCapDegPerSecond, 1e-6, 'speed cap');
assertClose(result.Metrics.Agreement, expected.Agreement, 1e-6, 'agreement');
assertClose(result.Metrics.Sensitivity, expected.Sensitivity, 1e-6, 'sensitivity');
assertClose(result.Metrics.Specificity, expected.Specificity, 1e-6, 'specificity');
assertClose(result.Metrics.Precision, expected.Precision, 1e-6, 'precision');
assertClose(result.Metrics.Jaccard, expected.Jaccard, 1e-6, 'Jaccard index');
assert(isfile(outputFile), 'Validation figure was not exported.');

disp(struct2table(result.Metrics));
fprintf('MATLAB July 21 validation passed. Figure: %s\n', outputFile);
close(result.Figure);


function assertClose(actual, expected, tolerance, label)
    assert(abs(actual - expected) <= tolerance, ...
        'Unexpected %s: got %.12g, expected %.12g.', label, actual, expected);
end
